    // AMENDED v16 - FormWorkflowCatalog.Documentation.cs   (AMENDS the v10 / v12 file)
    //
    // ============================ WHY v16 WAS NECESSARY ============================
    // This part file owns TWO of the three amendment items, and v12 had only half-applied
    // them:
    //
    //  ITEM 1 - "Automated Forms (No Approver Required)": Rev. Status (MNT-1420) and Task
    //           Card (MNT-1420C) already carry IsAutoGenerated = true and already declare
    //           the drafting step ONLY, so FormWorkflowCatalog.FirstStatusAfterSubmit()
    //           returns ApprovalStatus.Approved and the instance closes on submission.
    //           WHAT WAS MISSING: neither form declared AutoGeneratedSource, even though
    //           FormWorkflowDefinition.AutoGeneratedSource exists precisely so the Table Of
    //           Contents can render WHY the row has no approver (v14 contract, surfaced by
    //           FormWorkflowCatalog.AutoGeneratedSourceOf / AutoGeneratedReference()).
    //           Without it the ToC badge falls back to the literal "external source system"
    //           and the two rows become indistinguishable to a user.
    //           And ValidateDocumentationSection() never asserted the "no approver" rule, so
    //           a future edit could silently re-attach an approval chain to an automated row.
    //
    //  ITEM 2 (SB part) - "DOCUMENTATION (4 forms) - Service Bulletins (SB): Service
    //           Bulletins are expected to be approved by the Documentation Team Leader. Due
    //           to workload, the system should allow the Team Leader to assign the form to a
    //           Documentation Clerk for review. Once confirmed by the clerk, the
    //           Documentation Team Leader will issue final approval."
    //           THIS WAS NOT IMPLEMENTED AT ALL. v12 amended only the 918 / 918A steps
    //           (Regulatory) and the HR Manager steps (Training). The MNT-1420A DL sign-off
    //           step (SBStepLeaderSignOff) had AllowsDelegatedReview = false, so
    //           FormWorkflowCatalog.CanRequestDelegatedReview() returned false for the DL
    //           and the requested behaviour was unreachable - even though v14 had already
    //           created WorkflowRoleSets.DocumentationClerkOnly for exactly this step and
    //           granted the DL Permissions.RequestDelegatedReview plus the clerk
    //           Permissions.ConfirmDelegatedReview.
    //
    // NOTE ON WHY THE EXISTING CLERK STEP IS NOT THE SAME THING
    //   MNT-1420A already routes DL -> Clerk (step 3, PendingDocumentationClerk) -> DL
    //   (step 4, sign-off). That is the clerk PROCESSING the register line, i.e. data entry
    //   before the sign-off exists. The amendment asks for something different: at the
    //   SIGN-OFF step the DL wants a clerk to REVIEW what is about to be signed, then get it
    //   back and sign it himself. Modelling that as another routing step would move the
    //   sign-off and change the printed signature layout; modelling it as the delegated-review
    //   EXCURSION of step 4 keeps StepNo, Status and SignatureBlockType.SignedOffBy exactly
    //   where they were, so the printed block still stamps the DL's name, date and signature.
    //
    // ============================ WHAT v16 CHANGES, AND ONLY THIS ============================
    //   1. MNT-1420A step 4 (DL final review and sign-off):
    //        AllowsDelegatedReview           = true
    //        DelegatedReviewRoles            = DocumentationClerkOnly
    //        DelegatedReviewRequiresComments = true
    //      AllowsDelegation stays false (it already was): the sign-off is never handed over,
    //      only a reviewer is borrowed. Both facts are asserted by
    //      FormWorkflowCatalog.Validate() rules (b) - (g).
    //   2. MNT-1420 and MNT-1420C declare AutoGeneratedSource.
    //   3. New step-number constant SBStepLeaderSignOff is reused as the delegated-review
    //      anchor, plus the helper API DelegatedReviewStepNo(...) so no controller hard-codes
    //      a step number.
    //   4. ValidateDocumentationSection() now asserts item 1 (automated rows really carry no
    //      approver) and item 2 (the DL sign-off really can borrow a clerk reviewer).
    //   5. The "exactly four forms" section assertion is corrected: it now counts the four
    //      DOCUMENTATION form types instead of every row whose Section is DOCUMENTATION.
    //      The ATA record (FormWorkflowCatalog.Regulatory.cs, ATARecordFormType) is also
    //      placed in this section by design, so the v10 count of 5 always reported a false
    //      positive - which is exactly the kind of noise that makes a real Validate()
    //      failure get ignored.
    //
    // ADDITIVE / NON-BREAKING
    //   - Same namespace, same partial class, same single method DocumentationForms().
    //   - Same public constants (CmmDocumentationFormType, FormNoSB, FormNoAD, FormNoCMM,
    //     FormNoTaskCard, every step-number and field-name constant) so existing references
    //     keep compiling.
    //   - No enum, no status, no role and no permission is renamed or renumbered.
    //
    // ==================== WHAT v10 ALREADY FIXED (kept, unchanged) ====================
    //   MNT-1420A was split into FOUR explicit steps (1 unit receipt, 2 clerk assignment,
    //   3 clerk processing, 4 DL sign-off) instead of collapsing routing steps 1 and 2, so
    //   PendingDocumentationTeam and PendingAssignment are both reachable and the unit
    //   reception timestamp is recorded separately from the clerk assignment.
    //   MNT-1420B keeps STL sole authority (single role + AllowsDelegation = false +
    //   NotSkippable on every step).
    // =====================================================================================

