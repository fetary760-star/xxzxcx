            DelegatedReviewStepsFor(formType)
                .Select(s => (int?)s.StepNo)
                .FirstOrDefault();

        /// <summary>
        /// True when a Documentation Team ticket must be created for this form on submit,
        /// i.e. the form is routed through the unit.
        /// </summary>
        public static bool RequiresDocumentationTicket(string? formType) =>
            RoutesThroughDocumentationUnit(formType);

        /// <summary>
        /// MNT-1420A only: the "Others" category initiation rule.
        /// Returns true when the drafting payload satisfies it (or when the rule does not
        /// apply to this form type).
        /// </summary>
        public static bool IsInitiationCategoryValid(
            string? formType,
            IReadOnlyDictionary<string, string?>? formFields)
        {
            if (!string.Equals(formType, FormNodeTypes.SB, StringComparison.OrdinalIgnoreCase))
                return true;

            if (formFields is null) return false;
            if (!formFields.TryGetValue(FieldInitiationCategory, out var raw)) return false;

            return DocumentationInitiationCategories.IsOthers(raw);
        }

        /// <summary>
        /// Draft-time payload keys a form requires before it may be submitted.
        /// Empty when the form declares none.
        /// </summary>
        public static string[] RequiredDraftFieldsFor(string? formType) =>
            Get(formType)?.RequiredDraftFields ?? Array.Empty<string>();

        /// <summary>Payload keys a specific step requires before it may be completed.</summary>
        public static string[] RequiredFieldsForStep(string? formType, int stepNo) =>
            StepAt(formType, stepNo)?.RequiredFields ?? Array.Empty<string>();

        /// <summary>
        /// The payload keys that are still missing. The engine returns
        /// WorkflowErrorCodes.CommentsRequired-style failures using this list, so the UI can
        /// highlight the exact fields.
        /// </summary>
        public static string[] MissingRequiredFields(
            IEnumerable<string> requiredFields,
            IReadOnlyDictionary<string, string?>? formFields)
        {
            var missing = new List<string>();

            foreach (var field in requiredFields)
            {
                if (formFields is null
                    || !formFields.TryGetValue(field, out var value)
                    || string.IsNullOrWhiteSpace(value))
                {
                    missing.Add(field);
                }
            }

            return missing.ToArray();
        }

        /// <summary>
        /// Sole-authority guard of MNT-1420B: exactly one canonical role owns every step,
        /// and no step may be delegated or skipped. Called by the startup self-check.
        /// </summary>
        public static bool IsSoleAuthorityForm(string? formType, string canonicalRole)
        {
            var steps = StepsFor(formType);
            if (steps.Length == 0) return false;

            return steps.All(s =>
                s.EligibleRoles.Length == 1
                && string.Equals(s.EligibleRoles[0], canonicalRole, StringComparison.OrdinalIgnoreCase)
                && !s.AllowsDelegation
                && s.Skip == SkipMode.NotSkippable);
        }

        /// <summary>
        /// Section-level self-check, called from FormWorkflowCatalog.Validate() or from a
        /// unit test. Catches a Documentation routing regression before production.
        ///
        /// AMENDED v16 - additionally asserts both amendment items owned by this file:
        ///   item 1: MNT-1420 and MNT-1420C really carry NO approval step and NO approver;
        ///   item 2: the MNT-1420A DL sign-off step really can borrow a Documentation Clerk
        ///           as a delegated reviewer, without giving the sign-off away.
        /// </summary>
        public static IReadOnlyList<string> ValidateDocumentationSection()
        {
            var problems = new List<string>();

            // ---- MNT-1420A: the three routing steps must all exist and be distinct ----
            var sb = Get(FormNodeTypes.SB);
            if (sb is null)
            {
                problems.Add($"{FormNoSB}: not catalogued.");
            }
            else
            {
                if (StepAt(FormNodeTypes.SB, SBStepUnitReceipt)?.Status
                    != ApprovalStatus.PendingDocumentationTeam)
                {
                    problems.Add($"{FormNoSB} step {SBStepUnitReceipt}: routing step 1 must park the " +
                                 "record in PendingDocumentationTeam.");
                }

                var assignStep = StepAt(FormNodeTypes.SB, SBStepClerkAssignment);
                if (assignStep is null || !assignStep.RequiresManualAssignment)
                {
                    problems.Add($"{FormNoSB} step {SBStepClerkAssignment}: routing step 2 must require " +
                                 "manual assignment of an available clerk.");
                }
                else if (!assignStep.AssignerRoles.Contains(OrgRoles.DocumentationTeamLeader,
                             StringComparer.OrdinalIgnoreCase))
                {
                    problems.Add($"{FormNoSB} step {SBStepClerkAssignment}: only the Documentation Team " +
                                 "Leader may assign the clerk.");
                }

                if (StepAt(FormNodeTypes.SB, SBStepClerkProcessing)?.Status
                    != ApprovalStatus.PendingDocumentationClerk)
                {
                    problems.Add($"{FormNoSB} step {SBStepClerkProcessing}: the clerk processing step is missing.");
                }

                var signOff = StepAt(FormNodeTypes.SB, SBStepLeaderSignOff);
                if (signOff?.Status != ApprovalStatus.PendingDocumentationLeaderSignOff)
                {
                    problems.Add($"{FormNoSB} step {SBStepLeaderSignOff}: routing step 3 must park the " +
                                 "record in PendingDocumentationLeaderSignOff.");
                }
                else
                {
                    // ---- AMENDMENT ITEM 2 (SB part): the DL may borrow a clerk REVIEWER ----
                    if (!signOff.HasDelegatedReview)
                    {
                        problems.Add($"{FormNoSB} step {SBStepLeaderSignOff}: the Documentation Team " +
                                     "Leader must be able to assign a Documentation Clerk to review " +
                                     "the entry before he issues the final approval " +
                                     "(AllowsDelegatedReview + DelegatedReviewRoles).");
                    }
                    else if (!signOff.DelegatedReviewRoles.Contains(OrgRoles.DocumentationClerk,
                                 StringComparer.OrdinalIgnoreCase))
                    {
                        problems.Add($"{FormNoSB} step {SBStepLeaderSignOff}: the delegated reviewer of " +
                                     "the sign-off must be a Documentation Clerk.");
                    }

                    if (signOff.AllowsDelegation)
                    {
                        problems.Add($"{FormNoSB} step {SBStepLeaderSignOff}: the final sign-off must " +
                                     "stay with the Documentation Team Leader " +
                                     "(AllowsDelegation = false); only the review may be delegated.");
                    }

                    if (signOff.Signature != SignatureBlockType.SignedOffBy)
                    {
                        problems.Add($"{FormNoSB} step {SBStepLeaderSignOff}: the sign-off step must own " +
                                     "SignatureBlockType.SignedOffBy so the Documentation Team " +
                                     "Leader's name, date and signature are displayed after the " +
                                     "clerk's review returns.");
                    }
                }

                if (!sb.RequiredDraftFields.Contains(FieldInitiationCategory, StringComparer.OrdinalIgnoreCase))
                {
                    problems.Add($"{FormNoSB}: the \"Others\" category rule requires " +
                                 $"'{FieldInitiationCategory}' in RequiredDraftFields.");
                }
            }

            // ---- MNT-1420B: STL sole authority ----
            if (Get(FormNodeTypes.AD) is null)
            {
                problems.Add($"{FormNoAD}: not catalogued.");
            }
            else if (!IsSoleAuthorityForm(FormNodeTypes.AD, OrgRoles.TeamLeader))
            {
                problems.Add($"{FormNoAD}: STL sole authority violated. Every step must list " +
                             "TeamLeader as its only eligible role, with AllowsDelegation = false " +
                             "and Skip = NotSkippable.");
            }
            else if (RoutesThroughDocumentationUnit(FormNodeTypes.AD))
            {
                problems.Add($"{FormNoAD}: must not route through the Documentation Team.");
            }

            // ---- AMENDMENT ITEM 1: Rev. Status and Task Cards carry NO approver ----
            foreach (var (formType, formNo) in new[]
                     {
                         (CmmDocumentationFormType, FormNoCMM),
                         (FormNodeTypes.TaskCard, FormNoTaskCard)
                     })
            {
                var form = Get(formType);
                if (form is null)
                {
                    problems.Add($"{formNo}: not catalogued.");
                    continue;
                }

                if (!form.IsAutoGenerated)
                {
                    problems.Add($"{formNo}: data is auto-generated from an external system, so the " +
                                 "form must declare IsAutoGenerated = true and therefore require no " +
                                 "approval process and no approver role.");
                }

                if (form.ApprovalSteps.Any())
                {
                    problems.Add($"{formNo}: an auto-generated form must declare no approval step " +
                                 $"(found {form.ApprovalSteps.Count()}).");
                }

                if (FirstStatusAfterSubmit(formType) != ApprovalStatus.Approved)
                {
                    problems.Add($"{formNo}: an auto-generated form must close on submission " +
                                 $"(FirstStatusAfterSubmit returned " +
                                 $"'{ApprovalStatusInfo.Label(FirstStatusAfterSubmit(formType))}').");
                }

                if (form.SupportsDelegatedReview)
                {
                    problems.Add($"{formNo}: an auto-generated form has no approver, therefore it must " +
                                 "not declare a delegated review.");
                }

                if (string.IsNullOrWhiteSpace(form.AutoGeneratedSource))
                {
                    problems.Add($"{formNo}: declare AutoGeneratedSource so the Table Of Contents can " +
                                 "show which external system the rows come from and why the row has " +
                                 "no approver.");
                }
            }

            // ---- The section must contain exactly the four documented forms ----
            // AMENDED v16: count the four DOCUMENTATION form types, not every row whose
            // Section is DOCUMENTATION - the ATA record is deliberately placed in the same
            // ToC section by FormWorkflowCatalog.Regulatory.cs.
            var missingCore = DocumentationCoreFormTypes.Where(t => !IsCatalogued(t)).ToArray();
            if (missingCore.Length > 0)
            {
                problems.Add("DOCUMENTATION section: expected 4 forms " +
                             $"({FormNoCMM}, {FormNoSB}, {FormNoAD}, {FormNoTaskCard}); " +
                             $"not catalogued: {string.Join(", ", missingCore)}.");
            }

            return problems;
        }
    }
