        /// <summary>Form types of the DOCUMENTATION section, in Table-of-Contents order.</summary>
        public static string[] DocumentationFormTypes() =>
            BySection(ToCSections.Documentation).Select(f => f.FormType).ToArray();

        /// <summary>True when the form belongs to the DOCUMENTATION section of the ToC.</summary>
        public static bool IsDocumentationForm(string? formType) =>
            string.Equals(SectionOf(formType), ToCSections.Documentation, StringComparison.OrdinalIgnoreCase);

        /// <summary>
        /// True when the form is routed THROUGH the central Documentation Team, i.e. at
        /// least one of its steps is owned by FunctionalUnits.Documentation.
        /// MNT-1420B deliberately returns false (STL sole authority), and so do the two
        /// auto-generated rows, which have no routing at all.
        /// </summary>
        public static bool RoutesThroughDocumentationUnit(string? formType) =>
            StepsFor(formType).Any(s =>
                string.Equals(s.AssignmentUnit, FunctionalUnits.Documentation,
                    StringComparison.OrdinalIgnoreCase));

        /// <summary>
        /// Statuses that place a record in the Documentation Team queue. Used by
        /// GET /api/documentation/queue and by the DL inbox badge.
        ///
        /// AMENDED v16 - PendingDelegatedReview is included on purpose: while the DL has a
        /// clerk reviewing the sign-off, the record is still work of the Documentation unit
        /// and must remain visible in its queue. The precise actor is resolved by
        /// FormWorkflowCatalog.ApproverRolesFor(formType, status, currentStepNo), which
        /// returns the reviewer pool of the parked step rather than the approver.
        /// </summary>
        public static readonly ApprovalStatus[] DocumentationQueueStatuses =
        {
            ApprovalStatus.PendingDocumentationTeam,
            ApprovalStatus.PendingAssignment,
            ApprovalStatus.PendingDocumentationClerk,
            ApprovalStatus.PendingDocumentationLeaderSignOff,
            ApprovalStatus.PendingDelegatedReview
        };

        /// <summary>
        /// Step number of the clerk-assignment step of a documentation form, or null when
        /// the form has no clerk assignment (MNT-1420B and the auto-generated rows).
        /// </summary>
        public static int? ClerkAssignmentStepNo(string? formType) =>
            StepsFor(formType)
                .Where(s => s.RequiresManualAssignment
                            && string.Equals(s.AssignmentUnit, FunctionalUnits.Documentation,
                                StringComparison.OrdinalIgnoreCase))
                .Select(s => (int?)s.StepNo)
                .FirstOrDefault();

        /// <summary>Step number of the clerk processing / verification step, or null.</summary>
        public static int? ClerkProcessingStepNo(string? formType) =>
            StepsFor(formType)
                .Where(s => s.Status == ApprovalStatus.PendingDocumentationClerk)
                .Select(s => (int?)s.StepNo)
                .FirstOrDefault();

        /// <summary>Step number of the DL final review and sign-off step, or null.</summary>
        public static int? DocumentationSignOffStepNo(string? formType) =>
            StepsFor(formType)
                .Where(s => s.Status == ApprovalStatus.PendingDocumentationLeaderSignOff)
                .Select(s => (int?)s.StepNo)
                .FirstOrDefault();

